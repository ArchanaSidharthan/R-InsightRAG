# 4. Run three methods for each topic
# ------------------------------------------------------------

all_results <- list()
counter <- 1L

for (i in seq_len(nrow(query_cases))) {
  
  qid <- query_cases$query_id[i]
  keywords <- topic_keywords[[qid]]
  
  # A. Original question with semantic retrieval.
  original_result <- run_retrieval(
    question_cases <- query_cases$original_question[i],
    query_id = qid,
    method_label = "Original semantic",
    keywords = keywords
  )
  
  # B. Expanded question with semantic retrieval.
  expanded_result <- run_retrieval(
    question = query_cases$expanded_question[i],
    query_id = qid,
    method_label = "Expanded semantic",
    keywords = keywords
  )
  
  # C. Expanded question with hybrid reranking.
  expanded_hybrid <- run_retrieval(
    question = query_cases$expanded_question[i],
    query_id = qid,
    method_label = "Expanded hybrid",
    keywords = keywords
  )
  
  all_results[[counter]] <- original_result
  counter <- counter + 1L
  
  all_results[[counter]] <- expanded_result
  counter <- counter + 1L
  
  all_results[[counter]] <- expanded_hybrid
  counter <- counter + 1L
  
  message("Finished ", qid)
}

all_results <- Filter(Negate(is.null), all_results)

