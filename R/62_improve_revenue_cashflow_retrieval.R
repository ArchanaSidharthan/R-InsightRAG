# 3. Helper functions
# ------------------------------------------------------------

count_keyword_matches <- function(txt, keywords) {
  if (is.na(txt) || !nzchar(txt)) return(0L)
  
  txt <- tolower(txt)
  
  as.integer(sum(vapply(
    keywords,
    function(term) grepl(tolower(term), txt, fixed = TRUE),
    logical(1)
  )))
}

run_retrieval <- function(question, query_id, method_label, keywords) {
  
  message("\nSearching: ", method_label)
  message("Question: ", question)
  
  results <- semantic_search(question, top_k = 100)
  
  if (is.null(results) || nrow(results) == 0) {
    warning("No results for ", method_label)
    return(NULL)
  }
  
  if (!"semantic_score" %in% names(results)) {
    if ("similarity" %in% names(results)) {
      results$semantic_score <- results$similarity
    } else {
      stop(
        "No semantic score column found. Available columns: ",
        paste(names(results), collapse = ", ")
      )
    }
  }
  
  if (!"chunk_text" %in% names(results)) {
    results <- dplyr::left_join(results, chunks, by = "chunk_id")
  }
  
  results$keyword_count <- vapply(
    results$chunk_text,
    count_keyword_matches,
    integer(1),
    keywords = keywords
  )
  
  max_count <- max(results$keyword_count, na.rm = TRUE)
  
  if (!is.finite(max_count) || max_count <= 0) {
    results$keyword_score <- 0
  } else {
    results$keyword_score <- results$keyword_count / max_count
  }
  
  results$hybrid_score <-
    0.70 * results$semantic_score +
    0.30 * results$keyword_score
  
  if (method_label == "Original semantic") {
    results <- results[
      order(results$semantic_score, decreasing = TRUE),
    ]
  } else if (method_label == "Expanded semantic") {
    results <- results[
      order(results$semantic_score, decreasing = TRUE),
    ]
  } else {
    results <- results[
      order(results$hybrid_score, decreasing = TRUE),
    ]
  }
  
  results <- head(results, 5)
  
  results$query_id <- query_id
  results$method <- method_label
  results$question_used <- question
  results$rank <- seq_len(nrow(results))
  results$relevant <- NA_integer_
  results$review_notes <- ""
  
  results
}

